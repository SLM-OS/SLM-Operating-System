#!/usr/bin/env python3
"""Generate the boot-test name -> suite index used by the test filter.

Usage: gen-test-index.py <output.c> <test source.c>...

For every top-level function `int test_suite_X(void)` (or a helper
function that a suite calls), collect the names passed to RUN_TEST() and
RUN_*_TEST() macros in its body. Tests found in a helper are attributed to
every suite that calls the helper (transitively). The harness uses the
index to enter only the suites that hold the filtered tests; a name not in
the index makes the harness walk every suite instead (slower, still
correct), so a parse miss here costs time, not correctness.

The output defines test_index_next_suite() and test_index_size(), which
override the weak empty versions in kernel/tests/test_filter.c.
"""

import re
import sys

FUNC_RE = re.compile(r'^(?:static\s+)?(?:int|void)\s+(\w+)\s*\(\s*void\s*\)\s*$')
FUNC_INLINE_RE = re.compile(r'^(?:static\s+)?(?:int|void)\s+(\w+)\s*\(\s*void\s*\)\s*\{\s*$')
RUN_RE = re.compile(r'\bRUN_\w*TEST\s*\(\s*(\w+)\s*\)')
CALL_RE = re.compile(r'\b(\w+)\s*\(')
DEFINE_RE = re.compile(r'^\s*#\s*define\b')


def strip_comments(text):
    text = re.sub(r'/\*.*?\*/', lambda m: '\n' * m.group(0).count('\n'), text,
                  flags=re.S)
    return re.sub(r'//[^\n]*', '', text)


def parse_functions(path):
    """Return {func: (tests[], calls set)} for top-level functions."""
    with open(path, encoding='utf-8', errors='replace') as fh:
        lines = strip_comments(fh.read()).split('\n')
    funcs = {}
    i = 0
    while i < len(lines):
        line = lines[i]
        m = FUNC_INLINE_RE.match(line)
        start = None
        if m:
            start = i + 1
        else:
            m = FUNC_RE.match(line)
            if m and i + 1 < len(lines) and lines[i + 1].strip() == '{':
                start = i + 2
        if start is None:
            i += 1
            continue
        name = m.group(1)
        tests = []
        calls = set()
        j = start
        while j < len(lines) and not lines[j].startswith('}'):
            body = lines[j]
            if not DEFINE_RE.match(body):
                tests.extend(RUN_RE.findall(body))
                calls.update(CALL_RE.findall(body))
            j += 1
        funcs.setdefault(name, ([], set()))
        funcs[name][0].extend(tests)
        funcs[name][1].update(calls)
        i = j + 1
    return funcs


def main():
    if len(sys.argv) < 3:
        sys.stderr.write(__doc__)
        return 2
    out = sys.argv[1]
    funcs = {}
    for path in sys.argv[2:]:
        for name, (tests, calls) in parse_functions(path).items():
            entry = funcs.setdefault(name, ([], set()))
            entry[0].extend(tests)
            entry[1].update(calls)

    suites = sorted(n for n in funcs if n.startswith('test_suite_'))

    # Tests reachable from each suite: its own RUN_TESTs plus those of any
    # helper it calls, transitively.
    pairs = []
    for suite in suites:
        seen = set()
        stack = [suite]
        names = []
        while stack:
            fn = stack.pop()
            if fn in seen or fn not in funcs:
                continue
            seen.add(fn)
            tests, calls = funcs[fn]
            names.extend(tests)
            for c in calls:
                if c != fn and c in funcs and not c.startswith('test_suite_'):
                    stack.append(c)
        for t in dict.fromkeys(names):
            pairs.append((t, suite))

    pairs.sort()
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('/* Generated by scripts/gen-test-index.py. Do not edit. */\n')
        fh.write('#include <stdint.h>\n#include <stddef.h>\n\n')
        fh.write('struct test_index_entry { const char *test; const char *suite; };\n\n')
        fh.write('static const struct test_index_entry test_index[] = {\n')
        for t, s in pairs:
            fh.write(f'    {{ "{t}", "{s}" }},\n')
        fh.write('};\n\n')
        fh.write('#define TEST_INDEX_COUNT (sizeof(test_index) / sizeof(test_index[0]))\n\n')
        fh.write('static int index_streq(const char *a, const char *b)\n{\n'
                 '    while (*a != 0 && *a == *b) { a++; b++; }\n'
                 '    return *a == *b;\n}\n\n')
        fh.write('const char *test_index_next_suite(const char *test_name, uint32_t *cursor);\n')
        fh.write('uint32_t test_index_size(void);\n\n')
        fh.write('const char *test_index_next_suite(const char *test_name, uint32_t *cursor)\n{\n'
                 '    if (test_name == NULL || cursor == NULL) {\n        return NULL;\n    }\n'
                 '    for (uint32_t i = *cursor; i < TEST_INDEX_COUNT; i++) {\n'
                 '        if (index_streq(test_index[i].test, test_name)) {\n'
                 '            *cursor = i + 1;\n'
                 '            return test_index[i].suite;\n'
                 '        }\n'
                 '    }\n'
                 '    *cursor = (uint32_t)TEST_INDEX_COUNT;\n'
                 '    return NULL;\n}\n\n')
        fh.write('uint32_t test_index_size(void)\n{\n'
                 '    return (uint32_t)TEST_INDEX_COUNT;\n}\n')
    return 0


if __name__ == '__main__':
    sys.exit(main())
