#!/usr/bin/env python3
"""Generate the C table of SLM kernels from scripts/cuda/slm/MANIFEST.json (#475).

The manifest says what each kernel's cubin needs: registers, shared memory,
parameter offsets. kernel/gpu/slm_prog.c encodes launches by hand, so this
checks the manifest's offsets against the layout that code assumes and refuses
a mismatch at build time rather than launching with a wrong cbuf.

    gen-slm-kernel-table.py <MANIFEST.json> <out.h>

SLM_SASS gives each kernel its place in the operator library:
op_kind = SLM_OP_KIND_BASE + index, dtype FP16, tier as in the manifest
(see build-operator-library.py --slm-manifest).
"""
import json
import sys

SLM_OP_KIND_BASE = 32

# kernel -> ordered (argument, cbuf offset) as slm_prog.c writes them.
MM = [("x", 0x160), ("W", 0x168), ("out", 0x170), ("bias", 0x178),
      ("K", 0x180), ("N", 0x184), ("B", 0x188), ("flags", 0x18C)]
SLM_SASS = {
    "slm_mm_q4k_hmma_b8": MM,
    "slm_mm_q4k_hmma_b64": MM,
    "slm_mm_q4k_simt": MM,
    "slm_mm_q6k_hmma_b8": MM,
    "slm_mm_q6k_hmma_b64": MM,
    "slm_mm_q6k_simt": MM,
    "slm_embed_q4k": [("ids", 0x160), ("table", 0x168), ("out", 0x170), ("K", 0x178), ("B", 0x17C)],
    "slm_embed_q6k": [("ids", 0x160), ("table", 0x168), ("out", 0x170), ("K", 0x178), ("B", 0x17C)],
    "slm_rmsnorm": [("x", 0x160), ("gamma", 0x168), ("out", 0x170), ("n", 0x178), ("B", 0x17C),
                    ("eps", 0x180)],
    "slm_add": [("a", 0x160), ("b", 0x168), ("out", 0x170), ("total", 0x178)],
    "slm_swiglu": [("gate", 0x160), ("up", 0x168), ("out", 0x170), ("total", 0x178)],
    "slm_rope": [("x", 0x160), ("out", 0x168), ("table", 0x170), ("pos", 0x178), ("nh", 0x180),
                 ("hd", 0x184), ("B", 0x188)],
    "slm_gqa": [("q", 0x160), ("k", 0x168), ("v", 0x170), ("pos", 0x178), ("out", 0x180),
                ("nhq", 0x188), ("nhkv", 0x18C), ("hd", 0x190), ("B", 0x194)],
}


def load(path):
    """Entries for SLM_SASS, in its order. SystemExit on any mismatch."""
    with open(path, encoding="utf-8") as f:
        entries = {e["name"]: e for e in json.load(f)["entries"]}
    out = []
    for name, want in SLM_SASS.items():
        e = entries.get(name)
        if e is None:
            raise SystemExit(f"{path}: no entry for {name}")
        got = [(a["name"], a["offset"]) for a in e["abi"]]
        if got != want:
            raise SystemExit(f"{path}: {name}: cbuf ABI {got}, slm_prog.c assumes {want}")
        if list(e["block"]) != [32, 1, 1]:
            raise SystemExit(f"{path}: {name}: block {e['block']}, slm_prog.c assumes 32,1,1")
        if e["cbuf0_size"] > 512:
            raise SystemExit(f"{path}: {name}: cbuf0 {e['cbuf0_size']} over the 512 B stride")
        out.append(e)
    return out


def main():
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    entries = load(sys.argv[1])
    lines = [
        "/* Generated by scripts/cuda/gen-slm-kernel-table.py. Do not edit. */",
        "#ifndef SLM_KERNELS_GEN_H",
        "#define SLM_KERNELS_GEN_H",
        f"#define SLM_OP_KIND_BASE {SLM_OP_KIND_BASE}u",
        f"#define SLM_SASS_COUNT {len(entries)}u",
    ]
    for i, e in enumerate(entries):
        lines.append(f"#define SLM_SASS_{e['name'][4:].upper()} {i}u")
    lines.append("/* name, tier (SLM_GPU_TIER_*), registers, shared memory rounded to the")
    lines.append(" * QMD's 256 B granule. */")
    lines.append("#define SLM_SASS_TABLE \\")
    for e in entries:
        tier = 1 if e["tier"] == "HMMA" else 2
        smem = (e["smem_bytes"] + 255) // 256 * 256
        lines.append(f"    {{ \"{e['name']}\", {tier}u, {e['regs']}u, {smem}u }}, \\")
    lines.append("")
    lines.append("#endif")
    with open(sys.argv[2], "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
