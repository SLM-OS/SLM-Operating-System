#!/usr/bin/env python3
"""Regenerate runtime/src/slm/unicode_tables.rs from llama.cpp's Unicode data.

The Qwen2 pre-tokenizer needs \\p{L} and \\p{N}. core has neither: its
is_alphabetic also accepts marks. The tables must agree with the reference the
tokenizer goldens came from, so they are derived from llama.cpp's own
src/unicode-data.cpp and not from whatever Unicode version a Python or Rust
toolchain happens to carry. Nothing here runs in CI; regenerate only when moving
to a newer reference (scripts/fixtures/slm/PROVENANCE.md names the commit).

    scripts/tools/slm-gen-unicode-tables.py --llama-cpp <dir>
"""

import argparse
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "runtime" / "src" / "slm" / "unicode_tables.rs"

# struct unicode_cpt_flags in llama.cpp src/unicode.h.
FLAG_NUMBER = 0x0002
FLAG_LETTER = 0x0004
MAX_CODEPOINTS = 0x110000

# The set char::is_whitespace implements (White_Space). Checked against the
# reference below, so the tokenizer can keep using core for whitespace.
WHITE_SPACE = {*range(0x9, 0xE), 0x20, 0x85, 0xA0, 0x1680, *range(0x2000, 0x200B),
               0x2028, 0x2029, 0x202F, 0x205F, 0x3000}


def section(text, name):
    m = re.search(name + r"\s*=\s*\{(.*?)\n\};", text, re.S)
    if not m:
        raise SystemExit(f"{name} not found")
    return m.group(1)


def ranges_with(flag, starts):
    out = []
    for (start, flags), (next_start, _) in zip(starts, starts[1:] + [(MAX_CODEPOINTS, 0)]):
        if not flags & flag:
            continue
        if out and out[-1][1] == start - 1:
            out[-1] = (out[-1][0], next_start - 1)
        else:
            out.append((start, next_start - 1))
    return out


def table(name, doc, ranges):
    lines = [f"/// {doc}", f"pub(crate) const {name}: &[(u32, u32)] = &["]
    for i in range(0, len(ranges), 4):
        row = " ".join(f"(0x{a:05X}, 0x{b:05X})," for a, b in ranges[i:i + 4])
        lines.append("    " + row)
    lines.append("];")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--llama-cpp", required=True, type=Path)
    args = ap.parse_args()
    text = (args.llama_cpp / "src" / "unicode-data.cpp").read_text()

    body = section(text, "unicode_ranges_flags")
    starts = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", body)]
    if starts[0][0] != 0 or starts != sorted(starts):
        raise SystemExit("unexpected unicode_ranges_flags shape")

    ws = {int(a, 16) for a in re.findall(r"0x([0-9A-Fa-f]+)", section(text, "unicode_set_whitespace"))}
    if ws != WHITE_SPACE:
        raise SystemExit(f"whitespace set differs from White_Space: {sorted(ws ^ WHITE_SPACE)}")

    # The contraction rule only looks for ASCII letters after a lowercase
    # mapping. to_ascii_lowercase is only equivalent if nothing else maps there.
    lower = re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", section(text, "unicode_map_lowercase"))
    for a, b in lower:
        a, b = int(a, 16), int(b, 16)
        if a >= 0x80 and chr(b) in "stmdrvel":
            raise SystemExit(f"U+{a:04X} lowercases to {chr(b)}")

    letters = ranges_with(FLAG_LETTER, starts)
    numbers = ranges_with(FLAG_NUMBER, starts)
    OUT.write_text(
        "//! Unicode categories for the Qwen2 pre-tokenizer. Generated by\n"
        "//! `scripts/tools/slm-gen-unicode-tables.py` from llama.cpp's\n"
        "//! `src/unicode-data.cpp`; do not edit by hand. Sorted inclusive ranges.\n\n"
        + table("LETTER_RANGES", "`\\p{L}`.", letters) + "\n\n"
        + table("NUMBER_RANGES", "`\\p{N}`.", numbers) + "\n"
    )
    print(f"{OUT}: {len(letters)} letter ranges, {len(numbers)} number ranges")


if __name__ == "__main__":
    main()
