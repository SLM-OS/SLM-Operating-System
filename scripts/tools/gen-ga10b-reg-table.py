#!/usr/bin/env python3
"""Generate a C register-write table from an nvgpu MMIO trace (#1088).

The trace comes from an nvgpu build whose nvgpu_writel/nvgpu_readl log
every access to the ftrace buffer with the calling HAL function (patch
and capture: ~/slmos-ref/derivatives/nvgpu-traces/). This script keeps
the writes between two trace lines, drops the functions named with
--skip (clock gating, PMU, address-dependent setup handled in C), and
emits them in order as `{offset, value}` entries grouped under a
comment naming the nvgpu function that performed them.

Usage:
  gen-ga10b-reg-table.py TRACE FIRST LAST NAME [--skip SUBSTR ...]
"""
import argparse
import re

ap = argparse.ArgumentParser()
ap.add_argument("trace")
ap.add_argument("first", type=int, help="first trace line (1-based)")
ap.add_argument("last", type=int, help="last trace line (inclusive)")
ap.add_argument("name", help="C array name")
ap.add_argument("--skip", nargs="*", default=[])
a = ap.parse_args()

line_re = re.compile(r"\b(W) ([0-9a-f]{6}) ([0-9a-f]{8}) (?:x\d+ )?(\S+)")
rows = []
with open(a.trace) as f:
    for n, line in enumerate(f, 1):
        if n < a.first or n > a.last:
            continue
        m = line_re.search(line)
        if not m:
            continue
        fn = m.group(4)
        if any(s in fn for s in a.skip):
            continue
        rows.append((int(m.group(2), 16), int(m.group(3), 16), fn))

print(f"/* Generated by scripts/tools/gen-ga10b-reg-table.py from trace lines")
print(f" * {a.first}..{a.last}; do not edit by hand. */")
print(f"const struct ga10b_reg_write {a.name}[] = {{")
prev = None
for off, val, fn in rows:
    if fn != prev:
        print(f"    /* {fn} */")
        prev = fn
    print(f"    {{ 0x{off:06x}u, 0x{val:08x}u }},")
print("};")
print(f"const unsigned {a.name}_count = sizeof({a.name}) / sizeof({a.name}[0]);")
