/*
 * Put a pixel at (x, y) with given color
 */
static void fb_putpixel(uint32_t x, uint32_t y, uint32_t color)
{
    if (x >= fb_info.width || y >= fb_info.height) {
        return;
    }

    uint32_t *pixel = (uint32_t *)(fb_info.addr + y * fb_info.pitch + x * 4);
    *pixel = color;
}

/*
 * Draw a single character at pixel position (px, py)
 */
static void fb_drawchar(uint32_t px, uint32_t py, char c, uint32_t fg, uint32_t bg)
{
    if (c < 32 || c > 126) {
        c = '?';
    }

    const uint8_t *glyph = font_8x16[c - 32];

    for (uint32_t row = 0; row < 16; row++) {
        uint8_t bits = glyph[row];
        for (uint32_t col = 0; col < 8; col++) {
            uint32_t color = (bits & (0x80 >> col)) ? fg : bg;
            fb_putpixel(px + col, py + row, color);
        }
    }
}

/*
 * Scroll the console up by one line
 */
static void fb_scroll(void)
{
    /*
     * Bail out if the framebuffer is too small to scroll. char_height must
     * fit within fb_info.height; otherwise the copy-up loop would have a
     * negative lower bound and underflow unsigned arithmetic.
     */
    if (fb_info.height < char_height) {
        return;
    }

    /*
     * Sanity check the geometry. `rows` is derived from
     * fb_info.height / char_height in fb_console_init and must remain
     * consistent with fb_info.height. A mismatch would mean rows was
     * computed from one geometry and the memory bounds from another.
     */
    ASSERT((uint64_t)fb_info.pitch * fb_info.height >= (uint64_t)fb_info.width * 4);
    ASSERT(rows * char_height <= fb_info.height);

    uint8_t *fb = (uint8_t *)fb_info.addr;

    /* Copy lines char_height..fb_info.height-1 up by char_height rows. */
    for (uint32_t y = char_height; y < fb_info.height; y++) {
        uint8_t *src = fb + y * fb_info.pitch;
        uint8_t *dst = fb + (y - char_height) * fb_info.pitch;
        for (uint32_t i = 0; i < fb_info.pitch; i++) {
            dst[i] = src[i];
        }
    }

    /*
     * Clear the last text line. Because rows = fb_info.height/char_height
     * truncates, fb_info.height can exceed rows*char_height by up to
     * char_height-1 pixels. Clear from (rows-1)*char_height through
     * fb_info.height so that trailing remainder pixels are also cleared;
     * the explicit `y < fb_info.height` bound guards against any rows
     * miscomputation.
     */
    uint32_t last_line_y = (rows - 1) * char_height;
    for (uint32_t y = last_line_y; y < fb_info.height; y++) {
        uint32_t *row = (uint32_t *)(fb_info.addr + y * fb_info.pitch);
        for (uint32_t x = 0; x < fb_info.width; x++) {
            row[x] = bg_color;
        }
    }
}

/*
 * Initialize framebuffer console
 * Called with Multiboot2 info structure to extract framebuffer info
 */
void fb_console_init(void *multiboot_info)
{
    /* Parse Multiboot2 info structure to find framebuffer tag */
    if (!multiboot_info) {
        return;
    }

    uint8_t *ptr = (uint8_t *)multiboot_info;
    uint32_t total_size = *(uint32_t *)ptr;
    ptr += 8;  /* Skip size and reserved fields */

    while ((uintptr_t)ptr < (uintptr_t)multiboot_info + total_size) {
        uint32_t tag_type = *(uint32_t *)ptr;
        uint32_t tag_size = *(uint32_t *)(ptr + 4);

        if (tag_type == 0) {
            break;  /* End tag */
        }

        if (tag_type == 8) {  /* Framebuffer tag */
            fb_info.addr = *(uint64_t *)(ptr + 8);
            fb_info.pitch = *(uint32_t *)(ptr + 16);
            fb_info.width = *(uint32_t *)(ptr + 20);
            fb_info.height = *(uint32_t *)(ptr + 24);
            fb_info.bpp = *(uint8_t *)(ptr + 28);
            fb_info.type = *(uint8_t *)(ptr + 29);

            if (fb_info.type == 1 && fb_info.bpp == 32) {
                /* RGB direct color mode */
                fb_info.red_pos = *(uint8_t *)(ptr + 30);
                fb_info.red_size = *(uint8_t *)(ptr + 31);
                fb_info.green_pos = *(uint8_t *)(ptr + 32);
                fb_info.green_size = *(uint8_t *)(ptr + 33);
                fb_info.blue_pos = *(uint8_t *)(ptr + 34);
                fb_info.blue_size = *(uint8_t *)(ptr + 35);
            }
            break;
        }

        /* Move to next tag (8-byte aligned) */
        ptr += (tag_size + 7) & ~7;
    }

    /* Calculate console dimensions */
    if (fb_info.width && fb_info.height) {
        cols = fb_info.width / char_width;
        rows = fb_info.height / char_height;

        /* Clear screen */
        uint32_t *fb = (uint32_t *)fb_info.addr;
        uint32_t pixels = fb_info.width * fb_info.height;
        for (uint32_t i = 0; i < pixels; i++) {
            fb[i] = bg_color;
        }
    }
}

/*
 * Output a single character to the framebuffer console.
 *
 * Concurrency invariant: this function mutates shared cursor state
 * (cursor_x, cursor_y) and calls fb_scroll which mutates the shared
 * framebuffer region. It is NOT internally synchronized.
 *
 * On x86-64 (the only platform that uses fb_console) all callers reach
 * this function via uart_putc/uart_puts/uart_printf, which are serialized
 * by the UART_LOCK spinlock in kprintf.c. Do not call fb_console_putc or
 * fb_console_puts directly from a context that is not already holding
 * UART_LOCK — concurrent calls from multiple CPUs will race on cursor
 * state and corrupt the framebuffer.
 *
 * Unlocked fallbacks (uart_puts_unlocked, uart_printf_unlocked) also call
 * this function and are reserved for panic handlers / very early boot
 * where only one CPU is running.
 */
void fb_console_putc(char c)
{
    if (!fb_info.addr || !cols || !rows) {
        return;
    }

    if (c == '\n') {
        cursor_x = 0;
        cursor_y++;
    } else if (c == '\r') {
        cursor_x = 0;
    } else if (c == '\t') {
        cursor_x = (cursor_x + 8) & ~7;
    } else if (c == '\b') {
        if (cursor_x > 0) {
            cursor_x--;
        }
    } else {
        fb_drawchar(cursor_x * char_width, cursor_y * char_height, c, fg_color, bg_color);
        cursor_x++;
    }

    /* Handle line wrap */
    if (cursor_x >= cols) {
        cursor_x = 0;
        cursor_y++;
    }

    /* Handle scroll */
    if (cursor_y >= rows) {
        fb_scroll();
        cursor_y = rows - 1;
    }
}

/*
 * Output a string to the framebuffer console
 */
void fb_console_puts(const char *s)
{
    while (*s) {
        fb_console_putc(*s++);
    }
}

/*
 * Get framebuffer info (for debugging)
 */
void fb_console_get_info(uint32_t *width, uint32_t *height, uint32_t *cols_out, uint32_t *rows_out)
{
    if (width) *width = fb_info.width;
    if (height) *height = fb_info.height;
    if (cols_out) *cols_out = cols;
    if (rows_out) *rows_out = rows;
}

